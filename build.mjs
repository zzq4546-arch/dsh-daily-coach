#!/usr/bin/env node
/* dsh-calendar-coach — client bundle builder.
 *
 * Two faces live in one package: the host half (lib/*.js) is plain ESM and needs
 * no build; the browser half must be ONE file served as /plugins/<id>/client.js.
 * Authoring one 5000-line file is not maintainable, so the browser half is three
 * script fragments concatenated here:
 *
 *   src/coach.js     -> var COACH = (function () { ... })();   the merged daily coach
 *   src/calendar.js  -> var CAL   = (function () { ... })();   calendar pane + reminder card
 *   src/shell.js     -> function apply(ctx) { ... }            slots wiring / mode switch / polling
 *
 * Fragments must obey CONTRACT.md §1: ES5 style, no import/export, no top-level
 * document.body writes, exactly one top-level binding each.
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const PLUGIN_ID = 'dsh-calendar-coach'
const PARTS = [
  { file: 'src/coach.js', binding: 'COACH' },
  { file: 'src/calendar.js', binding: 'CAL' },
  { file: 'src/shell.js', binding: 'apply' },
]

const problems = []
const chunks = []

for (const part of PARTS) {
  const abs = join(root, part.file)
  let text
  try {
    text = readFileSync(abs, 'utf8')
  } catch {
    problems.push(`${part.file}: missing`)
    continue
  }
  const body = text.trim()
  if (body === '') {
    problems.push(`${part.file}: empty`)
    continue
  }
  if (/^\s*(import|export)\s/m.test(body)) problems.push(`${part.file}: contains import/export (CONTRACT §1.1)`)
  if (!new RegExp(`(var ${part.binding}\\b|function ${part.binding}\\s*\\()`).test(body)) {
    problems.push(`${part.file}: must expose top-level binding "${part.binding}" (CONTRACT §1.2)`)
  }
  if (/window\.__ModuleLoader__/.test(body)) problems.push(`${part.file}: must not touch __ModuleLoader__`)
  const bodyAppend = (body.match(/document\.body\.appendChild/g) || []).length
  if (bodyAppend > 0 && part.file === 'src/calendar.js') {
    problems.push(`${part.file}: must not append to document.body (${bodyAppend} occurrences)`)
  }
  chunks.push(`/* ===== ${part.file} (${body.length} bytes) ===== */\n${body}`)
}

if (problems.length > 0) {
  console.error('[build] refused to emit client.js:')
  for (const p of problems) console.error('  - ' + p)
  process.exit(1)
}

const out = `/* dsh-calendar-coach — browser half. GENERATED by build.mjs from src/*.js; edit the sources, not this file. */
window.__ModuleLoader__.load({
  id: '${PLUGIN_ID}',
  factory(require) {
    'use strict';
${chunks.join('\n\n')}

    /* 与 dsh-boot-echo 一致的已验证写法：声明注入 slots（cordis 的 inject 只支持数组或「服务名→配置」映射，
       对象形式的 required/optional 在这里会被当成"需要一个叫 required 的服务"，会把插件挂死在 PENDING）。
       layout（面板导航）故意不写进 inject：官方对它的可选访问方式就是 ctx.get("layout")，
       写进 inject 反而会多一个"服务没就绪就永远 PENDING"的风险。 */
    return { inject: ['slots'], apply: apply };
  }
});
`

const target = join(root, 'client.js')
writeFileSync(target, out, 'utf8')
const bytes = statSync(target).size
console.log(`[build] client.js ${bytes} bytes from ${PARTS.length} fragments`)
