# tools/gen-lunar-table.ps1 — 用 Windows/.NET 的标准农历表生成 lib/lunar-table.js
#
# 为什么不用 Intl：CLDR 的中国农历在部分年份与官方历法差一天
# （例：2027 春节 CLDR 给 2027-02-07，官方与 .NET 都是 2027-02-06）。
# .NET 的 ChineseLunisolarCalendar 用的就是国内通行的农历表，覆盖 1901-02-19 ~ 2101-01-28。
#
# 生成的表结构（每项 = 农历年，按 YEAR_START 起顺序排列）：
#   [ newYearDayOfYear, leapMonth, len1, len2, ... len12|13 ]
#   newYearDayOfYear: 正月初一在公历该年的第几天（1=1月1日）
#   leapMonth: 0 表示无闰月，否则是该年闰几月（1..12）
#   lenN: 每个农历月的天数（29/30），按「正月、二月…、闰X月…」的实际顺序排列
$ErrorActionPreference = 'Stop'
$c = New-Object System.Globalization.ChineseLunisolarCalendar
$YEAR_START = 1901
$YEAR_END = 2100

$start = [datetime]::new(1901, 2, 19)   # .NET 农历表支持的最早一天
$end = [datetime]::new(2101, 1, 27)

$years = [System.Collections.Generic.SortedDictionary[int, object]]::new()
$d = $start
$lastKey = ''
$currentYear = -1
$current = $null

while ($d -le $end) {
    $ly = $c.GetYear($d)
    $raw = $c.GetMonth($d)
    $leapOfYear = $c.GetLeapMonth($ly)
    $isLeap = ($leapOfYear -ne 0 -and $raw -eq $leapOfYear)
    if ($leapOfYear -ne 0 -and $raw -gt $leapOfYear) { $nm = $raw - 1 } else { $nm = $raw }

    if ($ly -ne $currentYear) {
        $currentYear = $ly
        # .NET 的 GetLeapMonth 用"原始月序"（闰六月 = 7），这里统一成"闰几月"（闰六月 = 6）
        $leapNorm = if ($leapOfYear -gt 0) { $leapOfYear - 1 } else { 0 }
        $current = [ordered]@{
            start   = $d
            leap    = $leapNorm
            lengths = [System.Collections.Generic.List[int]]::new()
            last    = ''
        }
        $years[$ly] = $current
        $lastKey = ''
    }

    $key = "$nm/$isLeap"
    if ($key -ne $lastKey) {
        $current.lengths.Add(1)
        $lastKey = $key
    }
    else {
        $current.lengths[$current.lengths.Count - 1]++
    }
    $d = $d.AddDays(1)
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('/* dsh-calendar-coach — 农历表。GENERATED by tools/gen-lunar-table.ps1 from')
[void]$sb.AppendLine(' * System.Globalization.ChineseLunisolarCalendar; 不要手改。')
[void]$sb.AppendLine(' * 每项 = [正月初一的年内序号(1=1月1日), 闰月(0=无), 各月天数...]，下标 = 农历年 - YEAR_START。')
[void]$sb.AppendLine(' */')
[void]$sb.AppendLine("export const YEAR_START = $YEAR_START")
[void]$sb.AppendLine('export const LUNAR = [')
foreach ($kv in $years.GetEnumerator()) {
    $ly = $kv.Key
    $v = $kv.Value
    $doy = $v.start.DayOfYear
    $lens = ($v.lengths | ForEach-Object { $_ }) -join ','
    $total = 0
    foreach ($x in $v.lengths) { $total += $x }
    $want = if ($v.leap -gt 0) { 13 } else { 12 }
    if ($v.lengths.Count -ne $want) { throw "year $ly has $($v.lengths.Count) months (expected $want)" }
    if ($total -lt 350 -or $total -gt 400) { throw "year $ly has $total days" }
    [void]$sb.AppendLine("  [$doy, $($v.leap), $lens], // $ly ($($v.lengths.Count) 月, $total 天)")
}
[void]$sb.AppendLine(']')

$out = Join-Path $PSScriptRoot '..\lib\lunar-table.js'
$sb.ToString() | Set-Content -Path $out -Encoding utf8NoBOM -NoNewline
Write-Output "wrote $out ($((Get-Item $out).Length) bytes, $($years.Count) years)"
